#!/usr/bin/env node
// Sandbox is generated from membership, the only source of business logic.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..'),source=path.join(root,'cloudfunctions/membership'),target=path.join(root,'cloudfunctions/membership_sandbox');
const outputs=new Map();
for(const name of ['index.js','lib/payment.js','lib/service.js','lib/repository.js','package.json','config.json','.gitignore','.env.example','database.rules.json','database.indexes.json']){
 let text=fs.readFileSync(path.join(source,name),'utf8');
 if(name==='index.js'){
  if(!text.includes('payEnv:0')||!text.includes('process.env.VIRTUAL_APP_KEY'))throw Error('Sandbox generator source markers changed');
  text=text.replace('payEnv:0','payEnv:1').replace('process.env.VIRTUAL_APP_KEY','process.env.VIRTUAL_SANDBOX_APP_KEY');
 }
 if(name.endsWith('.js'))text='// GENERATED by tools/build-membership-sandbox.cjs; edit cloudfunctions/membership instead.\n'+text;
 if(name==='package.json')text=text.replace('decide-membership','decide-membership-sandbox');
 if(name==='.env.example')text=text.replace('VIRTUAL_APP_KEY=','VIRTUAL_SANDBOX_APP_KEY=');
 if(name==='database.rules.json'||name==='database.indexes.json'){
  const value=JSON.parse(text);text=JSON.stringify(Object.fromEntries(Object.entries(value).map(([key,item])=>['sandbox_'+key,item])),null,2)+'\n';
 }
 outputs.set(name,text);
}
for(const [name,text] of outputs){
 const file=path.join(target,name);
 if(process.argv.includes('--check')){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text)throw Error('Sandbox generated file out of date: '+name);}
 else {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,text);}
}
console.log(process.argv.includes('--check')?'Sandbox source parity checked':'Generated membership_sandbox');
