#!/usr/bin/env python3
"""提取 shaizi 原盅体/底盘/骰子网格、原始动画曲线与三段原音效。
运行：python tools/import-dice-scene.py --source <data.unity3d>
使用原包同目录 sharedassets0.resource；只读源项目。
"""
import argparse, hashlib, json, math, struct
from pathlib import Path
import UnityPy
from fmod_toolkit import raw_to_wav
ROOT=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--source',type=Path,default=Path('/Users/apple/Desktop/开发资料/反编译相关/反编译项目/shaizi/app/src/main/assets/bin/Data/data.unity3d'))
a=p.parse_args();out=ROOT/'miniprogram/dice/assets';out.mkdir(exist_ok=True,parents=True)
env=UnityPy.load(str(a.source));binary=bytearray();meta={'meshes':{},'clips':{},'sourceMeshIds':{'cup':274,'tray':326,'die':330}}
for obj in env.objects:
 if obj.assets_file.name!='sharedassets0.assets':continue
 if obj.type.name=='Mesh' and obj.path_id in (274,326,330):
  name={274:'cup',326:'tray',330:'die'}[obj.path_id];positions=[];normals=[];indices=[]
  for line in obj.read().export().splitlines():
   if line.startswith('v '):positions.append([float(x)*(100 if name=='die' else 1) for x in line.split()[1:4]])
   elif line.startswith('vn '):normals.append([float(x) for x in line.split()[1:4]])
   elif line.startswith('f '):indices.extend(int(x.split('/')[0])-1 for x in line.split()[1:])
  assert len(positions)==len(normals) and len(positions)<65536
  scale=max(abs(x) for v in positions for x in v)/32767
  start=len(binary)
  for v,n in zip(positions,normals):
   color=[255]*4
   if name=='die':
    axis=max(range(3),key=lambda i:abs(v[i]));other=[abs(v[i]) for i in range(3) if i!=axis]
    pit=max(other)<.53 and (abs(v[axis])<.92 or abs(n[axis])<.97)
    if pit:color=[204,20,23,255] if axis==2 and v[2]<0 else [23,23,23,255]
   binary.extend(struct.pack('<6h4B',*[round(x/scale) for x in v],*[round(max(-1,min(1,x))*32767) for x in n],*color))
  offset=len(binary);binary.extend(struct.pack('<'+'H'*len(indices),*indices))
  while len(binary)%4:binary.append(0)
  meta['meshes'][name]={'vertexOffset':start,'vertexCount':len(positions),'indexOffset':offset,'indexCount':len(indices),'positionScale':scale}
 elif obj.type.name=='AnimationClip' and obj.path_id in (353,354,356):
  tree=obj.read_typetree();data=tree['m_MuscleClip']['m_Clip']['data'];stream=data['m_StreamedClip'];buf=struct.pack('<'+'I'*len(stream['data']),*stream['data']);pos=0;tracks=[[] for _ in range(stream['curveCount'])]
  while pos<len(buf):
   t,count=struct.unpack_from('<fi',buf,pos);pos+=8
   for _ in range(count):
    idx,*coef=struct.unpack_from('<i4f',buf,pos);pos+=20
    if math.isfinite(t) and t>=0:tracks[idx].append((t,coef))
  def value(index,t):
   if index>=stream['curveCount']:return data['m_ConstantClip']['data'][index-stream['curveCount']]
   keys=tracks[index];key=keys[0]
   for current in keys:
    if current[0]>t+1e-7:break
    key=current
   dt=max(0,t-key[0]);co=key[1];return ((co[0]*dt+co[1])*dt+co[2])*dt+co[3]
  bindings=tree['m_ClipBindingConstant']['genericBindings'];length=tree['m_MuscleClip']['m_StopTime'];frames=[]
  for frame in range(math.ceil(length*60)+1):
   t=min(length,frame/60);joints={489000808:{},1838834371:{}};channel=0
   for b in bindings:
    count=4 if b['attribute']==2 else 3
    v=[value(channel+i,t) for i in range(count)];channel+=count
    joints[b['path']][b['attribute']]=v
   # OBJ导出使用X反射，动画也映射到相同坐标系。
   values=[]
   for joint in [joints[489000808],joints[1838834371]]:
    tr=joint[1];q=joint[2];values.extend([-tr[0],tr[1],tr[2],q[0],-q[1],-q[2],q[3]])
   frames.append([round(t,6)]+[round(v,6) for v in values])
  meta['clips'][tree['m_Name']]={'duration':length,'frames':frames,'sourcePathId':obj.path_id}
if set(meta['meshes'])!={'cup','tray','die'} or set(meta['clips'])!={'rock_2','open_2','open_3'}:
 raise ValueError('未找到完整的原盅体、底盘、骰子及三段动作，停止导入')
resource=(a.source.parent/'sharedassets0.resource').read_bytes()
for name,offset,size in [('table',0,36384),('dice',36384,36608),('cup',72992,24128)]:
 samples=raw_to_wav(resource[offset:offset+size],name,2,44100)
 if len(samples)!=1:raise ValueError('音效导出不完整: '+name)
 (out/(name+'.wav')).write_bytes(next(iter(samples.values())))
(out/'scene.bin').write_bytes(binary)
(ROOT/'miniprogram/dice/scene.js').write_text('// Generated by tools/import-dice-scene.py. Do not hand edit.\nmodule.exports='+json.dumps(meta,separators=(',',':'))+';\n')
manifest={'sourceSha256':hashlib.sha256(a.source.read_bytes()).hexdigest(),'resourceSha256':hashlib.sha256(resource).hexdigest(),'meshes':meta['sourceMeshIds'],'animations':{k:v['sourcePathId'] for k,v in meta['clips'].items()},'outputs':[]}
for file in [out/'scene.bin',out/'cup.wav',out/'dice.wav',out/'table.wav',ROOT/'miniprogram/dice/scene.js']:
 manifest['outputs'].append({'file':str(file.relative_to(ROOT)),'bytes':file.stat().st_size,'sha256':hashlib.sha256(file.read_bytes()).hexdigest()})
(ROOT/'docs/source-data/dice-scene.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print('原3D模型/原开合及摇动动画/三段完整原音效已导出',len(binary),'bytes')
